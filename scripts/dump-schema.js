#!/usr/bin/env node
/**
 * Dumps the live database structure to db/schema.sql.
 *
 * Exists because pg_dump isn't always installed, and because the schema was
 * never in version control — it lived only inside the running Render instance.
 * Run it after any structural change so the repo stays the source of truth:
 *
 *   npm run db:dump
 *
 * Structure only. No rows are read, so this is safe against production.
 * Wherever possible it asks Postgres to generate the DDL (pg_get_constraintdef,
 * pg_get_viewdef, ...) rather than assembling strings by hand.
 */
require('dotenv').config();
const fs = require('fs');
const path = require('path');
const postgres = require('postgres');

if (!process.env.DATABASE_URL) {
  console.error('DATABASE_URL is not set. Put it in .env first.');
  process.exit(1);
}

const sql = postgres(process.env.DATABASE_URL, { ssl: 'require', prepare: false });
const out = [];
const say = (s = '') => out.push(s);
const section = (title) => {
  say('');
  say('-- ' + '='.repeat(74));
  say(`-- ${title}`);
  say('-- ' + '='.repeat(74));
  say('');
};

(async () => {
  const [{ version }] = await sql`SELECT version()`;
  say('-- Schema dump of the Zoya construction marketplace database.');
  say('-- Generated by scripts/dump-schema.js — do not edit by hand.');
  say(`-- Generated: ${new Date().toISOString()}`);
  say(`-- Server: ${version.split(',')[0]}`);
  say('');

  // ---- Extensions (PostGIS matters here) ----------------------------------
  const exts = await sql`
    SELECT extname, extversion FROM pg_extension
    WHERE extname <> 'plpgsql' ORDER BY extname`;
  if (exts.length) {
    section('Extensions');
    for (const e of exts) say(`CREATE EXTENSION IF NOT EXISTS "${e.extname}";  -- ${e.extversion}`);
  }

  // ---- Enum types ----------------------------------------------------------
  const enums = await sql`
    SELECT t.typname, array_agg(e.enumlabel ORDER BY e.enumsortorder) AS labels
    FROM pg_type t
    JOIN pg_enum e ON e.enumtypid = t.oid
    JOIN pg_namespace n ON n.oid = t.typnamespace
    WHERE n.nspname = 'public'
    GROUP BY t.typname ORDER BY t.typname`;
  if (enums.length) {
    section('Enum types');
    for (const e of enums) {
      say(`CREATE TYPE ${e.typname} AS ENUM (${e.labels.map((l) => `'${l}'`).join(', ')});`);
    }
  }

  // ---- Tables --------------------------------------------------------------
  const tables = await sql`
    SELECT c.relname AS table_name
    FROM pg_class c JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'public' AND c.relkind = 'r'
    ORDER BY c.relname`;

  section(`Tables (${tables.length})`);

  for (const { table_name } of tables) {
    const cols = await sql`
      SELECT a.attname AS name,
             format_type(a.atttypid, a.atttypmod) AS type,
             a.attnotnull AS not_null,
             pg_get_expr(d.adbin, d.adrelid) AS default_expr
      FROM pg_attribute a
      LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
      WHERE a.attrelid = ${table_name}::regclass
        AND a.attnum > 0 AND NOT a.attisdropped
      ORDER BY a.attnum`;

    const lines = cols.map((c) => {
      let l = `  ${c.name} ${c.type}`;
      if (c.default_expr) l += ` DEFAULT ${c.default_expr}`;
      if (c.not_null) l += ' NOT NULL';
      return l;
    });

    // Constraints as Postgres itself renders them
    const cons = await sql`
      SELECT conname, pg_get_constraintdef(oid) AS def, contype
      FROM pg_constraint
      WHERE conrelid = ${table_name}::regclass
      ORDER BY CASE contype WHEN 'p' THEN 1 WHEN 'u' THEN 2 WHEN 'f' THEN 3 ELSE 4 END, conname`;
    for (const c of cons) lines.push(`  CONSTRAINT ${c.conname} ${c.def}`);

    say(`CREATE TABLE ${table_name} (`);
    say(lines.join(',\n'));
    say(');');

    // Indexes that aren't already implied by a constraint
    const conNames = new Set(cons.map((c) => c.conname));
    const idx = await sql`
      SELECT indexname, indexdef FROM pg_indexes
      WHERE schemaname = 'public' AND tablename = ${table_name}
      ORDER BY indexname`;
    for (const i of idx) if (!conNames.has(i.indexname)) say(`${i.indexdef};`);

    const trg = await sql`
      SELECT tgname, pg_get_triggerdef(oid) AS def FROM pg_trigger
      WHERE tgrelid = ${table_name}::regclass AND NOT tgisinternal ORDER BY tgname`;
    for (const t of trg) say(`${t.def};`);

    say('');
  }

  // ---- Views ---------------------------------------------------------------
  const views = await sql`
    SELECT table_name FROM information_schema.views
    WHERE table_schema = 'public' ORDER BY table_name`;
  if (views.length) {
    section(`Views (${views.length})`);
    for (const v of views) {
      const [{ def }] = await sql`SELECT pg_get_viewdef(${v.table_name}::regclass, true) AS def`;
      say(`CREATE OR REPLACE VIEW ${v.table_name} AS\n${def}`);
      say('');
    }
  }

  // ---- Functions (skip anything the extensions brought in) -----------------
  const fns = await sql`
    SELECT p.proname, pg_get_functiondef(p.oid) AS def
    FROM pg_proc p
    JOIN pg_namespace n ON n.oid = p.pronamespace
    LEFT JOIN pg_depend dep ON dep.objid = p.oid AND dep.deptype = 'e'
    WHERE n.nspname = 'public' AND dep.objid IS NULL AND p.prokind = 'f'
    ORDER BY p.proname`;
  if (fns.length) {
    section(`Functions (${fns.length})`);
    for (const f of fns) { say(f.def + ';'); say(''); }
  }

  const target = path.join(__dirname, '..', 'db', 'schema.sql');
  fs.writeFileSync(target, out.join('\n').replace(/\n{3,}/g, '\n\n'), 'utf8');

  console.log(`Wrote ${path.relative(process.cwd(), target)}`);
  console.log(`  ${tables.length} tables, ${views.length} views, ${enums.length} enums, ${exts.length} extensions`);
  console.log('\nTables:');
  for (const t of tables) console.log('  ' + t.table_name);

  await sql.end();
})().catch(async (e) => {
  console.error('Dump failed:', e.message);
  try { await sql.end(); } catch {}
  process.exit(1);
});
